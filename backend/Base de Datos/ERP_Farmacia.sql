    ON DELETE CASCADE,
    CONSTRAINT FK_USUARIO_EMPLEADO FOREIGN KEY (EMPLEADO_ID) REFERENCES EMPLEADOS(ID)
    ON UPDATE CASCADE
    ON DELETE CASCADE
);

-- 1.10 TOKEN_RECUPERACION DE CONTRASEÑA
CREATE TABLE TOKEN_RECUPERACION (
    ID SERIAL PRIMARY KEY,
    USUARIO_ID INTEGER NOT NULL,

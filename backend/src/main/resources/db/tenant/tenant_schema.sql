
-- ============================================================================
-- MÓDULO 1: CONFIGURACIÓN, SUCURSALES Y SEGURIDAD INTERNA
-- ============================================================================

-- 1.1 CONFIGURACIÓN VISUAL Y DE APARIENCIA DE LA EMPRESA
CREATE TABLE CONFIGURACION_EMPRESA (
    ID SERIAL PRIMARY KEY,
    TEMA VARCHAR(30),
    COLOR_PRIMARIO VARCHAR(20),
    COLOR_SECUNDARIO VARCHAR(20),
    COLOR_ACENTO VARCHAR(20),
    TAMANO_FUENTE VARCHAR(10),
    TIPOGRAFIA VARCHAR(15),
    BORDES VARCHAR(15),
    LOGO BYTEA,
    LOGO_TIPO VARCHAR(30),
    LOGO_VERSION INTEGER NOT NULL DEFAULT 0,
    MODIFICADO_POR VARCHAR(100),
    LOGO_PERSONALIZADO_URL TEXT,
    ENCABEZADO_FACTURA TEXT,
    PIE_FACTURA TEXT,
    FECHA_MODIFICACION TIMESTAMP
);

-- 1.2 CIUDAD (CATÁLOGO GEOGRÁFICO DE LA EMPRESA)
CREATE TABLE CIUDAD (
    ID SERIAL PRIMARY KEY,
    NOMBRE VARCHAR(100) NOT NULL,
    PAIS VARCHAR(100) NOT NULL
);

-- 1.3 SUCURSALES DE LA EMPRESA
CREATE TABLE SUCURSAL (
    ID SERIAL PRIMARY KEY,
    CIUDAD_ID INTEGER NOT NULL,
    NOMBRE VARCHAR(120) NOT NULL,
    DIRECCION VARCHAR(255) NOT NULL,
    TELEFONO VARCHAR(30),
    HORA_APERTURA TIME,
    HORA_CIERRE TIME,
    ACTIVO BOOLEAN NOT NULL,
    CONSTRAINT FK_SUCURSAL_CIUDAD FOREIGN KEY (CIUDAD_ID) REFERENCES CIUDAD(ID)
    ON UPDATE CASCADE
    ON DELETE CASCADE
);

-- 1.4 MÓDULOS DEL SISTEMA
CREATE TABLE MODULO (
    ID SERIAL PRIMARY KEY,
    NOMBRE VARCHAR(100) NOT NULL
);

-- 1.5 FUNCIONES DEL MENÚ Y CASOS DE USO POR MÓDULO
CREATE TABLE FUNCION (
    ID SERIAL PRIMARY KEY,
    MODULO_ID INTEGER NOT NULL,
    NOMBRE VARCHAR(100) NOT NULL,
    CONSTRAINT FK_FUNCION_MODULO FOREIGN KEY (MODULO_ID) REFERENCES MODULO(ID)
    ON UPDATE CASCADE
    ON DELETE CASCADE
);

-- 1.6 ROLES DE USUARIO (ADMINISTRADOR, CAJERO, VENDEDOR, ETC.)
CREATE TABLE ROL (
    ID SERIAL PRIMARY KEY,
    NOMBRE VARCHAR(100) NOT NULL,
    PERMISO VARCHAR(100),
    ACTIVO BOOLEAN NOT NULL
);

-- 1.7 ROL_FUNCION (PERMISOS DE LECTURA / EDICIÓN POR FUNCIÓN)
CREATE TABLE ROL_FUNCION (
    ROL_ID INTEGER NOT NULL,
    FUNCION_ID INTEGER NOT NULL,
    DESCRIPCION VARCHAR(100) NOT NULL,

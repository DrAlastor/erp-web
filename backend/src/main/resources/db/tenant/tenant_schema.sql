    CONSTRAINT FK_ROL_FUNC_ROL FOREIGN KEY (ROL_ID) REFERENCES ROL(ID)
    ON UPDATE CASCADE
    ON DELETE CASCADE,
    CONSTRAINT FK_ROL_FUNC_FUNCION FOREIGN KEY (FUNCION_ID) REFERENCES FUNCION(ID)
    ON UPDATE CASCADE
    ON DELETE CASCADE
);

-- 1.8 EMPLEADOS DE LA EMPRESA
CREATE TABLE EMPLEADOS (
    ID SERIAL PRIMARY KEY,
    SUCURSAL_ID INTEGER NOT NULL,
    CI VARCHAR(30) UNIQUE NOT NULL,
    NOMBRE VARCHAR(100) NOT NULL,
    APELLIDO VARCHAR(100) NOT NULL,

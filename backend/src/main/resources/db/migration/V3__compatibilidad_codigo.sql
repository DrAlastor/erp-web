-- CU01/CU02: nombre visible y usuario de acceso (compartido/entity/Usuario)
ALTER TABLE usuario ADD COLUMN IF NOT EXISTS fullname VARCHAR(150);
ALTER TABLE usuario ADD COLUMN IF NOT EXISTS username VARCHAR(100);
UPDATE usuario SET username = split_part(email, '@', 1) WHERE username IS NULL OR username = '';

-- CU01: sesiones de renovación del JWT (cu01.../entity/Sesion)
CREATE TABLE IF NOT EXISTS sesion (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id         BIGINT       NOT NULL REFERENCES usuario (id) ON DELETE CASCADE,
    refresh_token_hash VARCHAR(255) NOT NULL,
    ip_origen          VARCHAR(45),
    user_agent         TEXT,
    fecha_inicio       TIMESTAMP,
    fecha_expiracion   TIMESTAMP    NOT NULL,
    fecha_cierre       TIMESTAMP
);

-- CU02/CU04/CU06/CU09: bitácora de auditoría (cu02.../entity/BitacoraLog)
CREATE TABLE IF NOT EXISTS bitacora_logs (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    accion              VARCHAR(50) NOT NULL,
    fecha_hora          TIMESTAMP   NOT NULL,
    usuario_responsable VARCHAR(50) NOT NULL,
    entidad             VARCHAR(50) NOT NULL,
    entidad_id          BIGINT      NOT NULL,
    ip_origen           VARCHAR(45)
);

-- CU09: almacenes (cu09.../entity/Almacen)
CREATE TABLE IF NOT EXISTS almacenes (
    id                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo             VARCHAR(50),
    nombre             VARCHAR(120) NOT NULL,
    direccion          VARCHAR(255),
    sucursal_id        INTEGER,
    capacidad_estimada NUMERIC(12, 2),
    es_principal       BOOLEAN      NOT NULL DEFAULT FALSE,
    activo             BOOLEAN      NOT NULL DEFAULT TRUE,
    empresa_id         UUID,
    fecha_creacion     TIMESTAMP
);

-- CU09: datos maestros con empresa (cu09.../entity/UnidadMedida, compartido Categoria)
ALTER TABLE unidades_medida ADD COLUMN IF NOT EXISTS empresa_id UUID;
ALTER TABLE categorias ADD COLUMN IF NOT EXISTS empresa_id UUID;

-- CU19: comprobante y anulación de ventas (ventas_y_facturacion/compartido/entity/Venta)
ALTER TABLE ventas ADD COLUMN IF NOT EXISTS tipo_comprobante VARCHAR(20) NOT NULL DEFAULT 'FACTURA';
ALTER TABLE ventas ADD COLUMN IF NOT EXISTS motivo_anulacion VARCHAR(200);
